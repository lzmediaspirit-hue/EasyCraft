import { readPref, writePref } from '../ui/prefs';

/*
 * מי הבעלים של השורה.
 *
 * עד כאן כל הטבלאות היו גלובליות: "כל הלקוחות" היו באמת כל הלקוחות
 * שבמכשיר, ולא היה שדה שאפשר לשאול לפיו "של מי זה". זה עובד בדיוק
 * כל עוד יש נגרייה אחת ומכשיר אחד — וזה הדבר הראשון שנשבר ברגע
 * שיש שרת: שאילתה בלי בעלות היא שאילתה שמחזירה את הנתונים של
 * מישהו אחר.
 *
 * לכן לכל שורה יש `workshopId`, וכל שאילתה עוברת דרכו. במכשיר
 * בודד זו תמיד אותה נגרייה, ולכן שום דבר לא משתנה בהתנהגות; מה
 * שמשתנה הוא שהגבול קיים, ואפשר לבדוק אותו.
 *
 * כאן נשמרת רק **הזהות** — איזו נגרייה פעילה עכשיו — ולא הנתונים
 * שלה. המודול הזה אינו מייבא את המסד במכוון: המסד מטביע לפיו, ולכן
 * תלות הפוכה הייתה מעגל.
 */

/**
 * הנגרייה שמגיעה עם ההתקנה.
 *
 * מזהה קבוע ולא אקראי, כדי שהמעבר במסד וזריעת ההתקנה הראשונה
 * יסכימו עליו בלי לתאם ביניהם. כשיהיה שרת, נגרייה אמיתית תקבל
 * מזהה משלו והמזהה הזה יישאר מה שהוא — המקומי.
 */
export const LOCAL_WORKSHOP = 'workshop-local';

const KEY = 'easycraft.workshop';

let current = readPref(KEY) || LOCAL_WORKSHOP;

/** הנגרייה שעובדים בה עכשיו. כל שורה חדשה נרשמת עליה. */
export function workshopId(): string {
  return current;
}

/**
 * מעבר לנגרייה אחרת.
 *
 * אין לזה עדיין מסך — יש נגרייה אחת במכשיר — והוא קיים כדי שההפרדה
 * תהיה דבר שאפשר להפעיל ולבדוק, ולא הבטחה. בשרת זה יגיע מהכניסה.
 */
export function useWorkshop(id: string): void {
  current = id;
  writePref(KEY, id);
}
