import type { CatalogGroup, RoomKind, UnitLevel } from '../db/types';
import { BEDROOM, KITCHEN, LIVING } from './standards';

/** מפרט מקוצר של פריט ספרייה שמגיע עם האפליקציה. */
export interface SeedItem {
  /** מזהה קבוע — כדי שעדכון האפליקציה לא ייצור כפילויות */
  key: string;
  rooms: RoomKind[];
  group: CatalogGroup;
  name: string;
  glyph: string;
  doors?: number;
  drawers?: number;
  drawerCols?: number;
  shelves?: number;
  level: UnitLevel;
  /** רוחב ברירת מחדל ורוחבי תקן נוספים */
  w: number;
  widths: number[];
  h: number;
  d: number;
  y: number;
  socle?: number;
  counter?: number;
  corner?: 'blindStart' | 'blindEnd' | 'lShape';
  blind?: number;
  panelThickness?: number;
  /** פריט נפוץ — מופיע בספרייה הראשית */
  common?: boolean;
  note?: string;
}

const K = KITCHEN;
const B = BEDROOM;
const V = LIVING;

/** רוחבי תקן נפוצים לארונות מטבח (מ"מ). */
const NARROW = [150, 200, 300, 350, 400, 450, 500, 600];
const WIDE = [600, 700, 800, 900, 1000, 1200];

const kitchenBase = (
  key: string,
  name: string,
  glyph: string,
  w: number,
  widths: number[],
  extra: Partial<SeedItem> = {},
): SeedItem => ({
  key,
  rooms: ['kitchen'],
  group: 'base',
  name,
  glyph,
  level: 'floor',
  w,
  widths,
  // גובה המשטח קובע: הארגז מגיע עד תחתית המשטח, והרגליים בתוכו
  h: K.counterTop - K.counterH,
  d: K.baseDepth,
  y: 0,
  socle: K.socleH,
  counter: K.counterH,
  ...extra,
});

const kitchenUpper = (
  key: string,
  name: string,
  glyph: string,
  w: number,
  widths: number[],
  extra: Partial<SeedItem> = {},
): SeedItem => ({
  key,
  rooms: ['kitchen'],
  group: 'upper',
  name,
  glyph,
  level: 'wall',
  w,
  widths,
  h: K.upperH,
  d: K.upperDepth,
  y: K.upperBottom,
  ...extra,
});

const kitchenTall = (
  key: string,
  name: string,
  glyph: string,
  w: number,
  widths: number[],
  extra: Partial<SeedItem> = {},
): SeedItem => ({
  key,
  rooms: ['kitchen'],
  group: 'tall',
  name,
  glyph,
  level: 'tall',
  w,
  widths,
  h: K.tallH,
  d: K.tallDepth,
  y: 0,
  socle: K.socleH,
  ...extra,
});

/** דופן או לוח בודד — נמדד ברוחב, בגובה ובעובי משלו. */
const panel = (
  key: string,
  name: string,
  w: number,
  widths: number[],
  h: number,
  thickness: number,
): SeedItem => ({
  key,
  rooms: ['kitchen', 'living', 'bedroom'],
  group: 'panel',
  name,
  glyph: 'plain',
  level: 'floor',
  w,
  widths,
  h,
  d: thickness,
  y: 0,
  panelThickness: thickness,
});

